// Writes the pages of the docs that come from the package itself, so that they cannot drift from it:
//   content/docs/examples/*          every example of examples/examples.js, one page per group
//   content/docs/reference/templates.mdx   every template with its options and defaults, from TEMPLATES
// Run it after changing the examples or the templates: npm run gen (in docs/) or npm run docs:gen (at the root).
import { mkdirSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { EXAMPLES } from '../../examples/examples.js';
import { TEMPLATES } from '../../src/index.js';

const content = new URL('../content/docs/', import.meta.url);
const HEAD = (from) => `{/* Generated by docs/scripts/gen-pages.mjs from ${from}: edit that, not this page. */}`;
const slug = (s) => s.toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[’']/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
// frontmatter strings, quoted for YAML
const q = (s) => JSON.stringify(s);
// a note as MDX: plain text with `code` spans. Outside the spans, MDX would read { as an expression, < as a tag,
// \ as an escape and * _ [ ] as markup, so those are escaped.
const mdxText = (s) => s.split(/(`[^`]*`)/).map((part, i) => (i % 2 ? part : part.replace(/[\\{}<>*_[\]]/g, '\\$&'))).join('');
const fence = (src, meta = 'source') => `\`\`\`feynman ${meta}\n${src}\n\`\`\``;

// ---------------- examples ----------------
const GROUPS = {
  Vocabulary: 'Line styles, vertex shapes, vertices labelled with their matrix elements, and the drafting grid.',
  'Self-energies': 'Fan–Migdal, Debye–Waller, Hartree, Fock and GW, lying down and standing up, with what goes inside the interaction.',
  'Hedin’s expansion and GT': 'Exchange diagrams of Hedin’s expansion, and the GT self-energy with its T matrix.',
  'Dyson equations': 'Dyson equations for the electron, the phonon and the photon, and W as an RPA series.',
  'Bubbles and excitons': 'Polarization bubbles, the phonon self-energy, excitons and RPA chains.',
  'Trions and biexcitons': 'Ladders of three and four lines: trions, biexcitons and your own few-body diagrams.',
  'Two-particle': 'Ladders, the Cooperon, the Bethe–Salpeter equation, the T matrix and the parquet decomposition.',
  'Vertex corrections': 'Vertex corrections to first and second order, and Hedin’s vertex.',
  'Particle physics': 'Tree-level scattering in the s, t and u channels, Compton scattering, pair annihilation, and QED, QCD, triangle and box loops.',
  'Written by hand': 'Diagrams written vertex by vertex, where no template fits.',
};
const groups = [...new Set(EXAMPLES.map((e) => e.group))];
const exDir = new URL('examples/', content);
mkdirSync(exDir, { recursive: true });
for (const f of readdirSync(exDir)) if (f.endsWith('.mdx') || f === 'meta.json') unlinkSync(new URL(f, exDir));

const pages = groups.map((g) => ({ group: g, slug: slug(g), examples: EXAMPLES.filter((e) => e.group === g) }));
for (const p of pages) {
  let out = `---\ntitle: ${q(p.group)}\ndescription: ${q(GROUPS[p.group] || `Examples: ${p.group}.`)}\n---\n\n${HEAD('examples/examples.js')}\n\n`;
  out += 'Each diagram is followed by its source. Where it uses a template, the **By hand** tab shows the same diagram written out vertex by vertex.\n\n';
  for (const ex of p.examples) out += `## ${mdxText(ex.title)}\n\n${ex.note ? mdxText(ex.note) + '\n\n' : ''}${fence(ex.source)}\n\n`;
  writeFileSync(new URL(`${p.slug}.mdx`, exDir), out);
}
let index = `---\ntitle: Examples\ndescription: ${q(`${EXAMPLES.length} diagrams with their sources, from the vocabulary of lines and vertices to GT and the parquet decomposition.`)}\n---\n\n${HEAD('examples/examples.js')}\n\n`;
index += 'Every example shows its source under the diagram. Copy it into a `feynman` code block, or open the **By hand** tab to see what a template draws, line by line.\n\n<Cards>\n';
for (const p of pages) index += `  <Card title=${q(p.group)} href="/docs/examples/${p.slug}">${mdxText(GROUPS[p.group] || '')} (${p.examples.length})</Card>\n`;
index += '</Cards>\n';
writeFileSync(new URL('index.mdx', exDir), index);
writeFileSync(new URL('meta.json', exDir), JSON.stringify({ title: 'Examples', pages: ['index', ...pages.map((p) => p.slug)] }, null, 2) + '\n');

// ---------------- the template reference ----------------
const typeOf = (v) => (typeof v === 'boolean' ? 'flag' : typeof v === 'number' ? 'number' : 'text');
const shown = (v) => (typeof v === 'boolean' ? (v ? 'on' : 'off') : v === '' ? '' : String(v));
let ref = `---\ntitle: Templates\ndescription: Every template, with its options and their defaults.\n---\n\n${HEAD('src/templates.js')}\n\n`;
ref += 'A template draws a whole diagram, or an equation, from one line: its name, then options written `key=value` (text in double quotes when it has spaces or TeX), and flags written as bare words. ';
ref += 'Options that are not listed are an error that names the ones there are. [Using templates](/docs/guides/templates) shows how to combine a template with statements of your own.\n\n';
ref += '| Template | What it draws |\n| --- | --- |\n';
for (const [name, t] of Object.entries(TEMPLATES)) ref += `| [\`${name}\`](#${slug(name)}) | ${mdxText(t.title).replace(/\|/g, '\\|')} |\n`;
for (const [name, t] of Object.entries(TEMPLATES)) {
  ref += `\n## \`${name}\`\n\n${mdxText(t.title)}.\n\n`;
  // options with their defaults; a backtick in a default would end its code span, so it goes without one
  ref += '| Option | Type | Default |\n| --- | --- | --- |\n';
  for (const [k, v] of Object.entries(t.params)) {
    const d = shown(v);
    ref += `| \`${k}\` | ${typeOf(v)} | ${d === '' ? '' : d.includes('`') ? mdxText(d) : `\`${d.replace(/\|/g, '\\|')}\``} |\n`;
  }
  ref += '\n';
  const flags = Object.entries(t.flags || {});
  if (flags.length) ref += `Flags: ${flags.map(([f, set]) => `\`${f}\` (${Object.entries(set).map(([k, v]) => `\`${k}=${v === true ? 'on' : v}\``).join(', ')})`).join(', ')}.\n\n`;
  ref += `${fence(t.example)}\n`;
}
mkdirSync(new URL('reference/', content), { recursive: true });
writeFileSync(new URL('reference/templates.mdx', content), ref);

console.log(`wrote examples/ (${pages.length} pages, ${EXAMPLES.length} examples) and reference/templates.mdx (${Object.keys(TEMPLATES).length} templates)`);
